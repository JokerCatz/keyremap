/* Host-side test for hid_parser.c using the JD-DZ.COM USB HANDLE descriptors.
 * Build and run: make test-firmware */
#include <assert.h>
#include <stdio.h>

#include "hid_parser.h"

static const uint8_t keyboard_desc[] = {
  0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
  0x75, 0x01, 0x95, 0x03, 0x91, 0x02, 0x95, 0x05, 0x91, 0x01, 0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7,
  0x95, 0x08, 0x81, 0x02, 0x75, 0x08, 0x95, 0x01, 0x81, 0x01, 0x19, 0x00, 0x29, 0x91, 0x26, 0xff,
  0x00, 0x95, 0x06, 0x81, 0x00, 0xc0,
};

static const uint8_t composite_desc[] = {
  0x09, 0xc7, 0xa1, 0x01, 0x05, 0xff, 0x85, 0xbc, 0x09, 0xc4, 0x15, 0x00, 0x26, 0xff, 0x00, 0x95,
  0x07, 0x75, 0x08, 0xb1, 0x02, 0x85, 0xbd, 0x96, 0x08, 0x01, 0xb1, 0x01, 0x85, 0xbe, 0x95, 0x07,
  0xb1, 0x01, 0xc0, 0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x85, 0x03, 0x05, 0x09, 0x19, 0x01, 0x29,
  0x05, 0x15, 0x00, 0x25, 0x01, 0x95, 0x05, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x03, 0x81,
  0x03, 0x05, 0x01, 0x09, 0x01, 0xa1, 0x00, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25,
  0x7f, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, 0x05, 0x0c, 0x0a, 0x38, 0x02, 0x75, 0x08, 0x95, 0x01,
  0x81, 0x06, 0xc0, 0xc0, 0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, 0x85, 0x01, 0x19, 0x00, 0x2a, 0x3c,
  0x02, 0x15, 0x00, 0x26, 0x3c, 0x02, 0x95, 0x01, 0x75, 0x10, 0x81, 0x00, 0xc0, 0x05, 0x01, 0x09,
  0x80, 0xa1, 0x01, 0x85, 0x02, 0x19, 0x81, 0x29, 0x83, 0x25, 0x01, 0x75, 0x01, 0x95, 0x03, 0x81,
  0x02, 0x95, 0x05, 0x81, 0x01, 0xc0,
};

static const hid_field_t *find(const hid_layout_t *layout, uint8_t report_id, uint16_t page, uint16_t usage) {
  for (uint8_t i = 0; i < layout->field_count; i++) {
    const hid_field_t *f = &layout->fields[i];
    if (f->report_id == report_id && f->usage_page == page && f->usage == usage) {
      return f;
    }
  }
  return NULL;
}

int main(void) {
  hid_layout_t layout;
  int32_t value;

  hid_parser_parse(keyboard_desc, sizeof(keyboard_desc), &layout);
  assert(!layout.uses_report_id);
  const hid_field_t *shift = find(&layout, 0, 0x07, 0xe1);
  assert(shift && shift->bit_offset == 1 && shift->bit_size == 1);
  const hid_field_t *keys = find(&layout, 0, 0x07, 0x00);
  assert(keys && (keys->flags & HID_FIELD_ARRAY) && keys->bit_offset == 16 && keys->count == 6);
  const uint8_t kb_report[] = {0x02, 0x00, 0x14, 0x1a, 0, 0, 0, 0};
  assert(hid_parser_read(shift, 0, kb_report, sizeof(kb_report), &value) && value == 1);
  assert(hid_parser_read(keys, 1, kb_report, sizeof(kb_report), &value) && value == 0x1a);

  hid_parser_parse(composite_desc, sizeof(composite_desc), &layout);
  assert(layout.uses_report_id);
  const hid_field_t *b1 = find(&layout, 3, 0x09, 1);
  const hid_field_t *b5 = find(&layout, 3, 0x09, 5);
  const hid_field_t *x = find(&layout, 3, 0x01, 0x30);
  const hid_field_t *y = find(&layout, 3, 0x01, 0x31);
  const hid_field_t *wheel = find(&layout, 3, 0x01, 0x38);
  const hid_field_t *pan = find(&layout, 3, 0x0c, 0x238);
  const hid_field_t *consumer = find(&layout, 1, 0x0c, 0x00);
  assert(b1 && b1->bit_offset == 0);
  assert(b5 && b5->bit_offset == 4);
  assert(x && x->bit_offset == 8 && (x->flags & HID_FIELD_SIGNED) && (x->flags & HID_FIELD_RELATIVE));
  assert(y && y->bit_offset == 16);
  assert(wheel && wheel->bit_offset == 24);
  assert(pan && (pan->flags & HID_FIELD_RELATIVE));
  assert(consumer && (consumer->flags & HID_FIELD_ARRAY) && consumer->bit_size == 16);

  /* Report ID 3 body (ID byte stripped): button 1, x=-5, y=+7, wheel=-1 */
  const uint8_t mouse_body[] = {0x01, 0xfb, 0x07, 0xff, 0x00};
  assert(hid_parser_read(b1, 0, mouse_body, sizeof(mouse_body), &value) && value == 1);
  assert(hid_parser_read(x, 0, mouse_body, sizeof(mouse_body), &value) && value == -5);
  assert(hid_parser_read(y, 0, mouse_body, sizeof(mouse_body), &value) && value == 7);
  assert(hid_parser_read(wheel, 0, mouse_body, sizeof(mouse_body), &value) && value == -1);
  assert(!hid_parser_read(wheel, 0, mouse_body, 2, &value));

  const uint8_t consumer_body[] = {0xe9, 0x00};
  assert(hid_parser_read(consumer, 0, consumer_body, sizeof(consumer_body), &value) && value == 0xe9);

  hid_parser_boot_mouse(&layout);
  const uint8_t boot_mouse[] = {0x02, 0x10, 0xf0};
  x = find(&layout, 0, 0x01, 0x30);
  assert(hid_parser_read(x, 0, boot_mouse, sizeof(boot_mouse), &value) && value == 16);
  wheel = find(&layout, 0, 0x01, 0x38);
  assert(!hid_parser_read(wheel, 0, boot_mouse, sizeof(boot_mouse), &value));

  puts("hid_parser: all tests passed");
  return 0;
}
